import { fileURLToPath } from "node:url";
import type { Schema } from "../../packages/sdk/src/openresponses/schema.ts";

const root = new URL("../../", import.meta.url);
const source = await Bun.file(
  new URL("protocol/openresponses/source.json", root),
).json();
const bytes = await Bun.file(
  new URL("protocol/openresponses/openapi.json", root),
).bytes();
if (
  new Bun.CryptoHasher("sha256").update(bytes).digest("hex") !== source.sha256
)
  throw new Error("OpenResponses snapshot digest differs from source.json");
const document = JSON.parse(new TextDecoder().decode(bytes));
if (document.info.version !== source.version)
  throw new Error("Protocol version mismatch");
const schemas: Record<string, Schema> = document.components.schemas;
const annotations = new Set([
  "description",
  "title",
  "default",
  "example",
  "examples",
  "discriminator",
]);
const keywords = new Set([
  "$ref",
  "type",
  "enum",
  "properties",
  "required",
  "additionalProperties",
  "items",
  "anyOf",
  "oneOf",
  "allOf",
  "minLength",
  "maxLength",
  "pattern",
  "minimum",
  "maximum",
  "minItems",
  "maxItems",
  "maxProperties",
]);
function normalize(value: Schema): Schema {
  const result: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value)) {
    if (annotations.has(key) || key.startsWith("x-")) continue;
    if (!keywords.has(key))
      throw new Error("Unsupported schema keyword: " + key);
    if (
      key === "$ref" &&
      (!String(entry).startsWith("#/components/schemas/") ||
        !schemas[String(entry).split("/").at(-1)!])
    )
      throw new Error("Unknown schema reference: " + entry);
    if (key === "properties")
      result[key] = Object.fromEntries(
        Object.entries(entry as Record<string, Schema>).map(
          ([name, schema]) => [name, normalize(schema)],
        ),
      );
    else if (["oneOf", "anyOf", "allOf"].includes(key))
      result[key] = (entry as Schema[]).map(normalize);
    else if (
      ["items", "additionalProperties"].includes(key) &&
      typeof entry === "object"
    )
      result[key] = normalize(entry as Schema);
    else result[key] = entry;
  }
  return result as Schema;
}
function type(value: Schema): string {
  if (value.$ref) return value.$ref.split("/").at(-1)!;
  if (value.enum) return value.enum.map((v) => JSON.stringify(v)).join(" | ");
  for (const [key, operator] of [
    ["anyOf", " | "],
    ["oneOf", " | "],
    ["allOf", " & "],
  ] as const)
    if (value[key]) return "(" + value[key]!.map(type).join(operator) + ")";
  switch (value.type) {
    case "null":
      return "null";
    case "string":
      return "string";
    case "boolean":
      return "boolean";
    case "number":
    case "integer":
      return "number";
    case "array":
      return "(" + type(value.items ?? {}) + ")[]";
    case "object": {
      const properties = Object.entries(value.properties ?? {});
      const fields = properties
        .map(
          ([name, property]) =>
            `${JSON.stringify(name)}${value.required?.includes(name) ? "" : "?"}: ${type(property)};`,
        )
        .join("\n");
      const extra = value.additionalProperties;
      if (typeof extra === "object")
        return properties.length
          ? `({${fields}} & Record<string, ${type(extra)}>)`
          : `Record<string, ${type(extra)}>`;
      return properties.length ? `{\n${fields}\n}` : "Record<string, unknown>";
    }
    case undefined:
      return "unknown";
    default:
      throw new Error("Unsupported type: " + value.type);
  }
}
const normalized = Object.fromEntries(
  Object.entries(schemas).map(([name, value]) => [name, normalize(value)]),
);
const events = Object.keys(schemas).filter((name) =>
  name.endsWith("StreamingEvent"),
);
const header = `// Generated by scripts/protocol/generate.ts v1. Do not edit.\n// OpenResponses ${source.version}, ${source.commit}; Apache-2.0.\n// Snapshot SHA-256: ${source.sha256}\n`;
const outputs = {
  "types.ts":
    header +
    Object.entries(normalized)
      .map(([name, value]) => `export type ${name} = ${type(value)};`)
      .join("\n\n") +
    `\nexport type StreamingEvent = ${events.join(" | ")};\nexport interface ProtocolTypes {\n${Object.keys(
      schemas,
    )
      .map((name) => `${name}: ${name};`)
      .join("\n")}\n}\n`,
  "schemas.ts":
    header +
    'import type { Schema } from "./schema.ts";\nimport type { ProtocolTypes } from "./types.ts";\n' +
    `export const schemas: Record<keyof ProtocolTypes, Schema> = ${JSON.stringify(normalized)};\nexport const eventSchemas = ${JSON.stringify(Object.fromEntries(events.map((name) => [schemas[name]!.properties!.type!.enum![0], name])))} as const;\n`,
};
for (const [name, content] of Object.entries(outputs)) {
  const path = new URL("packages/sdk/src/openresponses/" + name, root);
  const formatter = Bun.spawn(
    [
      process.execPath,
      "fmt",
      "--no-script",
      "--stdin-filepath",
      fileURLToPath(path),
    ],
    { stdin: new Response(content), stdout: "pipe", stderr: "pipe" },
  );
  const formatted = await new Response(formatter.stdout).text();
  const errors = await new Response(formatter.stderr).text();
  if (await formatter.exited)
    throw new Error("Protocol formatter failed: " + errors);
  if (process.argv.includes("--check")) {
    if (
      !(await Bun.file(path).exists()) ||
      (await Bun.file(path).text()) !== formatted
    )
      throw new Error(
        "Generated protocol drift: " + name + "; run bun run protocol:generate",
      );
  } else await Bun.write(path, formatted);
}
console.log(
  `OpenResponses ${source.version}: ${Object.keys(schemas).length} schemas, ${events.length} SSE events; ${process.argv.includes("--check") ? "verified" : "generated"}`,
);
